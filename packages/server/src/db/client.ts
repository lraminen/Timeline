import { fileURLToPath } from 'node:url';
import { mkdirSync } from 'node:fs';
import type { PgDatabase, PgQueryResultHKT } from 'drizzle-orm/pg-core';
import * as schema from './schema.js';
import { runDataMigrations, type DataMigrationResult } from './data-migrations.js';
import type { Config } from '../config.js';

/** Either driver (PGlite or node-postgres) behind one type. */
export type Db = PgDatabase<PgQueryResultHKT, typeof schema>;

export interface Database {
  db: Db;
  driver: 'pglite' | 'postgres';
  /** Applies pending SQL migrations, then pending data migrations; returns the data migrations that ran. */
  migrate: () => Promise<DataMigrationResult[]>;
  close: () => Promise<void>;
}

/** SQL migrations generated by drizzle-kit (`pnpm db:generate`). */
const MIGRATIONS = fileURLToPath(new URL('../../drizzle', import.meta.url));

/**
 * Opens the database: PostgreSQL when `DATABASE_URL` is set, otherwise an
 * embedded PGlite (real Postgres compiled to WebAssembly) — persisted in
 * `DATA_DIR`, or in memory when that is unset (tests, quick local runs).
 */
export async function openDatabase(
  config: Pick<Config, 'DATABASE_URL' | 'DATA_DIR'>,
): Promise<Database> {
  if (config.DATABASE_URL) {
    const { default: pg } = await import('pg');
    const { drizzle } = await import('drizzle-orm/node-postgres');
    const { migrate } = await import('drizzle-orm/node-postgres/migrator');
    const pool = new pg.Pool({ connectionString: config.DATABASE_URL, max: 10 });
    const db = drizzle({ client: pool, schema });
    return {
      db: db as unknown as Db,
      driver: 'postgres',
      migrate: async () => {
        await migrate(db, { migrationsFolder: MIGRATIONS });
        return runDataMigrations(db);
      },
      close: () => pool.end(),
    };
  }

  const { PGlite } = await import('@electric-sql/pglite');
  const { drizzle } = await import('drizzle-orm/pglite');
  const { migrate } = await import('drizzle-orm/pglite/migrator');
  if (config.DATA_DIR) mkdirSync(config.DATA_DIR, { recursive: true });
  const client = new PGlite(config.DATA_DIR);
  const db = drizzle({ client, schema });
  return {
    db: db as unknown as Db,
    driver: 'pglite',
    migrate: async () => {
      await migrate(db, { migrationsFolder: MIGRATIONS });
      return runDataMigrations(db);
    },
    close: () => client.close(),
  };
}
